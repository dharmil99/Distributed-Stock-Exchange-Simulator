"""
Trade Statistics Data Structures.

Defines canonical structured containers for symbol-level metrics and aggregate
market analytics generated by the Apache Spark distributed analytics pipeline (Lab 7).
"""

from dataclasses import dataclass, field, asdict
from typing import List, Dict, Any, Optional


@dataclass
class SymbolStatistics:
    """Summary statistics for a single traded ticker symbol."""
    symbol: str
    total_volume: int
    trade_count: int
    avg_price: float
    total_value: float
    min_price: float = 0.0
    max_price: float = 0.0

    def to_dict(self) -> Dict[str, Any]:
        return {
            "symbol": self.symbol,
            "total_volume": int(self.total_volume),
            "trade_count": int(self.trade_count),
            "avg_price": round(float(self.avg_price), 2),
            "total_value": round(float(self.total_value), 2),
            "min_price": round(float(self.min_price), 2),
            "max_price": round(float(self.max_price), 2),
        }


@dataclass
class TradeStatisticsReport:
    """Complete consolidated market analytics report."""
    total_trades: int = 0
    total_volume: int = 0
    total_traded_value: float = 0.0
    average_trade_price: float = 0.0
    most_traded_symbols: List[Dict[str, Any]] = field(default_factory=list)
    highest_value_symbols: List[Dict[str, Any]] = field(default_factory=list)
    symbol_statistics: List[Dict[str, Any]] = field(default_factory=list)
    time_statistics: List[Dict[str, Any]] = field(default_factory=list)
    metadata: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "total_trades": int(self.total_trades),
            "total_volume": int(self.total_volume),
            "total_traded_value": round(float(self.total_traded_value), 2),
            "average_trade_price": round(float(self.average_trade_price), 2),
            "most_traded_symbols": self.most_traded_symbols,
            "highest_value_symbols": self.highest_value_symbols,
            "symbol_statistics": self.symbol_statistics,
            "time_statistics": self.time_statistics,
            "metadata": self.metadata,
        }
